#ifndef _WIFI_DBG_H
#define _WIFI_DBG_H   
#include "ecnt_lib_dbg.h"

#define LIB_WIFI_ERROR(fmt, ...)     	ECNT_LIB_DBG_PRINT(ECNT_DBG_ERROR, ECNT_DBG_TYPE_WIFI, fmt, ##__VA_ARGS__)
#define LIB_WIFI_WARN(fmt, ...)    		ECNT_LIB_DBG_PRINT(ECNT_DBG_WARN, ECNT_DBG_TYPE_WIFI, fmt, ##__VA_ARGS__)
#define LIB_WIFI_NOTICE(fmt, ...)    	ECNT_LIB_DBG_PRINT(ECNT_DBG_NOTICE, ECNT_DBG_TYPE_WIFI, fmt, ##__VA_ARGS__)
#define LIB_WIFI_DEBUG(fmt, ...)     	ECNT_LIB_DBG_PRINT(ECNT_DBG_DEBUG, ECNT_DBG_TYPE_WIFI, fmt,##__VA_ARGS__)

#define WIFI_FUNC_TRACE_ENTER           LIB_WIFI_DEBUG("===Enter===\n") 

#define WIFIMGR_FAIL_MSG(fmt, ...)   \
    do{\
        LIB_WIFI_ERROR(fmt,##__VA_ARGS__); \
    }while(0)


#define RETURN_WIFIMGR_FAIL_MSG(fmt, ...)   \
    do{\
        LIB_WIFI_ERROR("===Fail Exit==="fmt,##__VA_ARGS__); \
        return ECNT_WIFIMGR_FAILURE; \
    }while(0)

#define RETURN_WIFIMGR_DEBUG_MSG(fmt, ...)   \
	do{\
		LIB_WIFI_DEBUG("===Debug Exit==="fmt,##__VA_ARGS__); \
		return ECNT_WIFIMGR_FAILURE; \
	}while(0)

#define RETURN_WIFIMGR_FAIL   \
    do{\
        LIB_WIFI_DEBUG("===Fail Exit===\n"); \
        return ECNT_WIFIMGR_FAILURE; \
    }while(0)

#define RETURN_WIFIMGR_SUCCESS \
    do{\
        LIB_WIFI_DEBUG("===Success Exit===\n"); \
        return ECNT_WIFIMGR_SUCCESS; \
    }while(0)

#endif
