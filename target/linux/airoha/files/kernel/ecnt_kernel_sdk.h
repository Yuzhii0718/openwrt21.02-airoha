#ifndef _LINUX_ECNT_KENREL_SDK_H
#define _LINUX_ECNT_KENREL_SDK_H
#include <ecnt_hook/ecnt_hook.h>
#if defined(TCSUPPORT_APPS_NOROOT_PERM)
#include <linux/user_namespace.h>
#include <linux/cred.h>
#include <common/ecnt_global_macro.h>
#endif


static inline int ecnt_ns_capable_inline_hook(struct user_namespace *ns, int cap, bool *ret_code)
{
#if defined(TCSUPPORT_APPS_NOROOT_PERM)
	struct cred *cred = current_cred();
	if ( ECNT_UID == __kuid_val(cred->uid) || ECNT_GID == __kgid_val(cred->gid) )
	{
		*ret_code = true;
		current->flags |= PF_SUPERPRIV;
		return ECNT_RETURN;
	}	

#endif

	return ECNT_CONTINUE;
}

#endif/*_LINUX_ECNT_KENREL_SDK_H*/